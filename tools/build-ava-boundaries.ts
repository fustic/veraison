// Turns the UC Davis American Viticultural Area outlines into the US region outlines the map
// draws, written to content/boundaries/us.json (committed, small). Source data is CC0:
// https://github.com/UCDavisLibrary/ava (file avas_aggregated_files/avas.geojson).
//
//   npm run map:us                                   # uses tools/boundaries/source/ava/avas.geojson
//   npm run map:us -- path/to/avas.geojson
//   npm run map:us -- --list                         # print every AVA name

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { regions } from '../content/index.ts';
import { simplifyRing, type Ring } from './boundaries/geo.ts';
import { AVA_FOR_REGION, STATE_EXTRAS, STATE_OF } from './boundaries/us-ava-regions.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const src = args.find((a) => !a.startsWith('--')) ?? join(ROOT, 'tools/boundaries/source/ava/avas.geojson');
const outFile = join(ROOT, 'content/boundaries/us.json');

type Props = { name: string; state: string | null; within: string | null; removed: string | null };
type Feature = { properties: Props; geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: unknown } };
const all = (JSON.parse(readFileSync(src, 'utf8')) as { features: Feature[] }).features.filter((f) => !f.properties.removed);

if (args.includes('--list')) {
  console.log(all.map((f) => `${f.properties.name}  (${f.properties.state}${f.properties.within ? `, in ${f.properties.within}` : ''})`).sort().join('\n'));
  process.exit(0);
}

const fold = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const byName = new Map(all.map((f) => [fold(f.properties.name), f]));
const polygonsOf = (f: Feature): Ring[][] =>
  f.geometry.type === 'Polygon' ? [f.geometry.coordinates as Ring[]] : (f.geometry.coordinates as Ring[][]);
const tolerance: Record<string, number> = { region: 0.004, district: 0.002, appellation: 0.0008 };

const out: Record<string, { ava: string[]; geometry: { type: 'MultiPolygon'; coordinates: Ring[][] } }> = {};
const missing: string[] = [];
for (const region of regions) {
  if (!region.id.startsWith('region:us-')) continue;
  const state = STATE_OF[region.id];
  const named = (names: string[]) => names.map((n) => byName.get(fold(n))).filter((f): f is Feature => !!f);
  const features = state
    ? [...all.filter((f) => (f.properties.state ?? '').trim() === state && !f.properties.within), ...named(STATE_EXTRAS[region.id] ?? [])]
    : named(AVA_FOR_REGION[region.id] ?? [region.name]);
  if (!features.length) {
    missing.push(region.id);
    continue;
  }
  const tol = tolerance[region.level] ?? 0.002;
  const coordinates = features
    .flatMap(polygonsOf)
    .map((poly) => poly.map((ring) => simplifyRing(ring.map(([x, y]) => [x, y] as [number, number]), tol)).filter((r): r is Ring => r !== null))
    .filter((rings) => rings.length > 0);
  if (coordinates.length) out[region.id] = { ava: features.map((f) => f.properties.name), geometry: { type: 'MultiPolygon', coordinates } };
}

writeFileSync(
  outFile,
  JSON.stringify({
    source: 'UC Davis Library, American Viticultural Areas Digitizing Project (CC0). https://github.com/UCDavisLibrary/ava',
    note: 'Official AVA boundaries, simplified. State regions combine their top-level AVAs. Generated by tools/build-ava-boundaries.ts; do not edit by hand.',
    regions: out,
  }),
);
console.log(`wrote ${Object.keys(out).length} US outlines to ${outFile}`);
if (missing.length) console.log(`No AVA found (add it to tools/boundaries/us-ava-regions.ts if there should be):\n  ${missing.join('\n  ')}`);
